#!/bin/bash
# setup_landcover.sh -- create and configure the evolving_landcover case: spinup, then eval.
#
# Inputs : setup/ctsm.env (resolution, project, $SEAN_FILES_SCRATCH: Sean's 1850
#          surface dataset and 1850-2023 land-use timeseries). Run from the CIME
#          scripts folder ($CIME_SCRIPTS in ctsm.env), where create_newcase is.
# Outputs: the case folder ./evolving_landcover, configured but not built
#          (HIST compset; fsurdat and flanduse_timeseries in user_nl_clm).
#
# Usage:
#   bash <repo>/setup/setup_landcover.sh spinup             # step 1: create + configure spinup
#   bash <repo>/setup/setup_landcover.sh eval 2002-10-01    # step 2: eval run

# ============================================================================
# RESOLVED (Aug 18, 2026):
# Compset HIST_DATM%NLDAS2_CLM60%SP_SICE_SOCN_MIZUROUTE_SGLC_SWAV works
# directly -- swapping DATM to %NLDAS2 (not the default %GSWP3v1) means the
# forcing-data question is answered without needing a datm.streams override.
#
# flanduse_timeseries / fsurdat for our 0.125nldas2 grid were generated by
# Sean (in $SEAN_FILES_SCRATCH) -- this unblocks the
# earlier "No default value found for flanduse_timeseries" build error.
# ============================================================================

# -h / --help prints the header block above
[[ "${1:-}" =~ ^(-h|--help)$ ]] && { sed -n '2,/^$/s/^# \{0,1\}//p' "$0"; exit 0; }

set -e
source "$(dirname "$0")/ctsm.env"   # settings and paths

mode=$1
casename="evolving_landcover"
compset_longname="HIST_DATM%NLDAS2_CLM60%SP_SICE_SOCN_MIZUROUTE_SGLC_SWAV"

SEAN_FILES="$SEAN_FILES_SCRATCH"
FLANDUSE="${SEAN_FILES}/landuse.timeseries_0.125nldas2_hist_1850-2023_78pfts_c260813.nc"
FSURDAT="${SEAN_FILES}/surfdata_0.125nldas2_hist_1850_78pfts_c260813.nc"

if [ "$mode" == "spinup" ]; then

    ./create_newcase \
        --case "$casename" \
        --compset "$compset_longname" \
        --driver "$DRIVER" \
        --compiler "$COMPILER" \
        --res "$RES" \
        --machine "$MACHINE" \
        --project "$PROJECT" \
        --run-unsupported

    cd "$casename"

    ./xmlchange DATM_YR_START=1980
    ./xmlchange DATM_YR_END=2018
    ./xmlchange DATM_YR_ALIGN=1980
    ./xmlchange RUN_TYPE=startup
    ./xmlchange RUN_STARTDATE=1980-10-01
    ./xmlchange CONTINUE_RUN=FALSE
    ./xmlchange STOP_OPTION=nyears
    ./xmlchange STOP_N=22
    ./xmlchange RESUBMIT=0
    ./xmlchange JOB_QUEUE=main --subgroup case.run
    ./xmlchange JOB_WALLCLOCK_TIME=08:00:00 --subgroup case.run

    ./case.setup

    cat >> user_nl_clm << EOF
hist_empty_htapes = .true.
hist_mfilt = 1,365
hist_nhtfrq = 0,-24
hist_fincl1 = 'BTRANMN','H2OSFC','H2OSNO','SNOWDP','ZWT','ZWT_PERCH','FROST_TABLE',
              'TWS','QDRAI','QOVER','QH2OSFC','QDRAI_PERCH','QVEGT','QVEGE','QSOIL',
              'QFLX_SNOW_DRAIN','SOILLIQ','SOILICE','TLAI','TBOT','TSA',
              'TG','TV','TSKIN','FPSN','FSH','EFLX_LH_TOT','EFLX_SOIL_GRND','FGR12',
              'FIRA','FIRE','FSNO','FH2OSFC','FSDS','RAIN','SNOW','TSOI','ALT',
              'QRUNOFF','TOTSOILLIQ','TOTSOILICE','QFLX_EVAP_TOT'
hist_fincl2 = 'BTRANMN','H2OSFC','H2OSNO','SNOWDP','ZWT','ZWT_PERCH','FROST_TABLE',
              'TWS','QDRAI','QOVER','QH2OSFC','QDRAI_PERCH','QVEGT','QVEGE','QSOIL',
              'QFLX_SNOW_DRAIN','SOILLIQ','SOILICE','TLAI','TBOT','TSA',
              'TG','TV','TSKIN','FPSN','FSH','EFLX_LH_TOT','EFLX_SOIL_GRND','FGR12',
              'FIRA','FIRE','FSNO','FH2OSFC','FSDS','RAIN','SNOW','TSOI','ALT',
              'QRUNOFF','TOTSOILLIQ','TOTSOILICE','QFLX_EVAP_TOT'

flanduse_timeseries = '${FLANDUSE}'
fsurdat = '${FSURDAT}'
EOF

    echo ""
    echo "Spinup case created and configured."
    echo "CHECK before building:"
    echo "  grep -i 'flanduse_timeseries\|fsurdat' ${SCRATCH}/${casename}/run/lnd_in"
    echo "  grep -i 'NLDAS\|GSWP' CaseDocs/datm.streams.txt.* 2>/dev/null"
    echo "Then: ./case.build && ./case.submit"

elif [ "$mode" == "eval" ]; then

    refdate=$2
    if [ -z "$refdate" ]; then
        echo "USAGE: ./setup_landcover.sh eval <RUN_REFDATE, e.g. 2002-10-01>"
        exit 1
    fi

    cd "$casename"

    ./xmlchange RUN_TYPE=hybrid
    ./xmlchange RUN_REFCASE="$casename"
    ./xmlchange RUN_REFDATE="$refdate"
    ./xmlchange GET_REFCASE=FALSE
    ./xmlchange RUN_STARTDATE=1980-10-01
    ./xmlchange CONTINUE_RUN=FALSE
    ./xmlchange STOP_OPTION=nyears
    ./xmlchange STOP_N=38
    ./xmlchange RESUBMIT=0
    ./xmlchange JOB_WALLCLOCK_TIME=12:00:00 --subgroup case.run

    ./case.setup --reset

    echo "Eval run configured from spinup restart $refdate."
    echo "Then: ./case.build && ./case.submit"

else
    echo "USAGE: ./setup_landcover.sh [spinup|eval <RUN_REFDATE>]"
    exit 1
fi